"""Rebuild src/core/hsn_sac_codes.txt from GSTN's published HSN and SAC masters.

Usage:
    python refresh_hsn_codes.py              # download the current workbook
    python refresh_hsn_codes.py master.xlsx  # or read one already downloaded

Standard library only, so it runs without the app's dependencies.
"""

import hashlib
import io
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

SOURCE_URL = "https://tutorial.gst.gov.in/downloads/HSN_SAC.xlsx"
OUTPUT = Path(__file__).parent / "src" / "core" / "hsn_sac_codes.txt"

# Far below the 22,510 codes of the April 2026 workbook. A smaller result means
# the layout changed, and writing it would flag most real codes as unknown.
MIN_EXPECTED_CODES = 15000

_SHEET = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"


def normalize_code(raw: str | None) -> str | None:
    """One master cell as a code an invoice could carry, or None if it can't be one."""
    # The workbook holds "2307 00" and "2514 00" with a stray space.
    code = (raw or "").replace(" ", "")
    if not code.isdigit():
        return None
    # A handful of chapter 01-09 codes lost their leading zero in Excel: "3074330"
    # is 03074330. An odd length can't be anything else, since GST has no such code.
    if len(code) in (5, 7):
        code = f"0{code}"
    # Chapter headings (2 digits) are in the master, but GST doesn't accept them.
    return code if len(code) in (4, 6, 8) else None


def parse_codes(workbook: zipfile.ZipFile) -> set[str]:
    """Every usable code in column A of every sheet, skipping each header row."""
    shared = [
        "".join(text.text or "" for text in item.iter(f"{_SHEET}t"))
        for item in ET.fromstring(workbook.read("xl/sharedStrings.xml"))
    ]
    codes: set[str] = set()
    for name in workbook.namelist():
        if not re.fullmatch(r"xl/worksheets/sheet\d+\.xml", name):
            continue
        for row in list(ET.fromstring(workbook.read(name)).iter(f"{_SHEET}row"))[1:]:
            for cell in row:
                value = cell.find(f"{_SHEET}v")
                if not cell.attrib.get("r", "").startswith("A") or value is None:
                    continue
                raw = shared[int(value.text)] if cell.attrib.get("t") == "s" else value.text
                code = normalize_code(raw)
                if code:
                    codes.add(code)
    return codes


def _modified_date(workbook: zipfile.ZipFile) -> str:
    match = re.search(rb"<dcterms:modified[^>]*>(\d{4}-\d{2}-\d{2})", workbook.read("docProps/core.xml"))
    return match.group(1).decode() if match else "unknown"


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        data = Path(argv[1]).read_bytes()
    else:
        # The server refuses urllib's default user agent.
        request = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request, timeout=60) as response:
            data = response.read()

    workbook = zipfile.ZipFile(io.BytesIO(data))
    codes = parse_codes(workbook)
    if len(codes) < MIN_EXPECTED_CODES:
        print(f"Found only {len(codes)} codes, so the workbook layout has probably changed. Nothing written.")
        return 1

    header = [
        "# GSTN's HSN and SAC masters. Generated by backend/refresh_hsn_codes.py, do not edit.",
        f"# Source: {SOURCE_URL}",
        f"# Workbook last modified: {_modified_date(workbook)}",
        f"# Workbook sha256: {hashlib.sha256(data).hexdigest()}",
    ]
    OUTPUT.write_text("\n".join(header + sorted(codes)) + "\n", encoding="ascii")
    print(f"Wrote {len(codes)} codes to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
